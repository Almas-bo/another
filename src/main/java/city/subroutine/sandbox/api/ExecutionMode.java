/** Режим запуска. */
public enum ExecutionMode {
    /** Компиляция, проверка байткода, контракт и тесты. */
    FULL,
    /**
     * Только компиляция, проверка байткода и контракта, без тестов. Быстрая обратная связь
     * для редактора при наборе кода (аналог диагностики LSP).
     */
    CHECK
}
