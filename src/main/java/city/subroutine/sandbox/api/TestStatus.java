package city.subroutine.sandbox.api;

/** Итог одного теста. Каждый статус мапится движком на свой визуальный сбой в симуляции. */
public enum TestStatus {
    PASSED,
    /** Проверка не прошла: неверный результат или не то исключение. */
    FAILED,
    /** Код игрока выбросил необработанное исключение. */
    ERROR,
    /** Тест не уложился в лимит времени (бесконечный цикл, livelock, медленный алгоритм). */
    TIMEOUT,
    /** Тест завис, и среди его потоков найден цикл взаимной блокировки. */
    DEADLOCK,
    /** Куча песочницы исчерпана во время этого теста. */
    MEMORY_LIMIT_EXCEEDED,
    /** Код игрока создал больше потоков, чем разрешено. */
    THREAD_LIMIT_EXCEEDED,
    /** Не запускался: песочница остановлена на предыдущем тесте. */
    SKIPPED,
    /** Процесс песочницы аварийно завершился во время теста. */
    SANDBOX_CRASH;

    public boolean passed() {
        return this == PASSED;
    }
}
